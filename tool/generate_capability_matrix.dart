import 'dart:convert';
import 'dart:io';

void main() {
  final root = Directory('device_profiles/batteries');
  final files = root.existsSync()
      ? root
            .listSync(recursive: true)
            .whereType<File>()
            .where((file) => file.path.endsWith('.json'))
            .toList()
      : <File>[];
  final rows = <String>[];
  for (final file in files) {
    final json = jsonDecode(file.readAsStringSync()) as Map<String, Object?>;
    final capabilities = json['capabilities'] as Map<String, Object?>;
    final models = (json['models'] as List).join(', ');
    final firmware = (json['firmware_ranges'] as List).join(', ');
    rows.add(
      '| ${json['manufacturer']} | $models | $firmware | ${capabilities['identify'] ?? 'unavailable'} | ${capabilities['read_live'] ?? 'unavailable'} | ${capabilities['read_config'] ?? 'unavailable'} | ${capabilities['write_parameter'] ?? 'unavailable'} | ${json['provenance'] is Map ? (json['provenance'] as Map)['document_id'] : 'none'} |',
    );
  }
  const targets = [
    'Pylontech',
    'Dyness',
    'Felicity Solar Lithium',
    'Growatt ARK',
    'Deye Lithium',
    'JK BMS',
    'JBD / Xiaoxiang',
    'Daly',
    'Seplos',
  ];
  for (final target in targets) {
    rows.add(
      '| $target | -- | -- | research-target | unavailable | unavailable | prohibited | documents and hardware required |',
    );
  }
  final output =
      '''# Capability matrix

Generated by `dart run tool/generate_capability_matrix.dart`. Do not edit manually.

| Manufacturer | Model | Firmware | Identify | Live telemetry | Configuration | Write | Evidence |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

No physical battery or inverter is represented as supported. `simulated` capabilities are valid only inside the deterministic simulator.
''';
  File('docs/CAPABILITY_MATRIX.md').writeAsStringSync(output);
}
